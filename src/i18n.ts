const catalogs: Record<Locale, Record<MessageKey, Formatter>> = { en, 'zh-CN': zh }

export function translate(locale: Locale, key: MessageKey, params: MessageParams = {}): string {
  return catalogs[locale][key](params)
}

export function translateDiagnostic(locale: Locale, item: Diagnostic): string {
  return translate(locale, item.code, item.params ?? {})
}

export function normalizeLocale(value: string | undefined): Locale | null {
  if (value === undefined) return null
  const normalized = value.trim().replace('_', '-').toLowerCase()
  if (normalized === 'zh' || normalized.startsWith('zh-')) return 'zh-CN'
  if (normalized === 'en' || normalized.startsWith('en-')) return 'en'
  return null
}

function macSystemLocale(platform: NodeJS.Platform): Locale | null {
  if (platform !== 'darwin') return null
  const result = spawnSync('defaults', ['read', '-g', 'AppleLanguages'], { encoding: 'utf8', timeout: 2_000 })
  if (result.status !== 0) return null
  return normalizeLocale(/"([^"]+)"/.exec(result.stdout)?.[1])
}

export interface LocaleOptions {
  explicit?: string
  env?: NodeJS.ProcessEnv
  platform?: NodeJS.Platform
  intlLocale?: string
}

export function resolveLocale(options: LocaleOptions = {}): Locale {
  const env = options.env ?? process.env
  const explicit = normalizeLocale(options.explicit)
  if (explicit !== null) return explicit
  const configured = normalizeLocale(env.DSH_KEEPER_LANG)
  if (configured !== null) return configured
  for (const candidate of [env.LC_ALL, env.LC_MESSAGES, env.LANG]) {
    if (candidate !== undefined && !/^(?:C|POSIX)(?:\.|$)/i.test(candidate)) {
      const locale = normalizeLocale(candidate)
      if (locale !== null) return locale
    }
  }
  const system = macSystemLocale(options.platform ?? process.platform)
  if (system !== null) return system
  return normalizeLocale(options.intlLocale ?? Intl.DateTimeFormat().resolvedOptions().locale) ?? 'en'
}
